"""
How deep in each method's gene ranking do the 50 PAM50 genes lie?

docs/report/03_data.md, "PAM50 gene recovery". The PAM50 label is computed
from 50 genes, so for each subtype-vs-rest task the genes that make the
label are known. Each method ranks all genes once per split, on the
training half, as in the runner. Recall at k is the share of the 50 among
the top k. The random control's expected recall is k / number of genes.

Lasso ranks only the genes with a non-zero weight; the rest are never
selected, so its recall stops growing there.

Usage:
    python scripts/pam50_recovery.py --n-splits 2 --out docs/pam50_recovery.md
"""

import argparse

import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.model_selection import StratifiedShuffleSplit
from sklearn.preprocessing import StandardScaler

from featsel.run import build_tasks
from featsel.selectors import (
    LassoSelector,
    MannWhitneySelector,
    RFESelector,
    TreeImportanceSelector,
)
from featsel_datasets.scanb_gse96058.featsel_view import load_xy
from featsel_datasets.scanb_gse96058.pam50 import PAM50_GENES

SEED = 42
K_VALUES = [10, 50, 100, 250, 500, 1000, 2500, 5000, 10000]


def methods(seed):
    """Each method as in configs/comparison_scanb.yaml, fit to the smallest k."""
    return {
        'MannWhitneySelector': MannWhitneySelector(n_features=10),
        'LassoSelector': LassoSelector(n_features=10, C=1.0, random_state=seed),
        'TreeImportanceSelector': TreeImportanceSelector(n_features=10, n_estimators=200,
                                                         random_state=seed),
        'RFESelector': RFESelector(n_features=10, C=0.01, step=0.5, random_state=seed),
    }


def ranks_of(selector, truth):
    """1-based rank of each truth gene in the selector's ranking; inf if never ranked."""
    importances = selector.feature_importances_
    order = np.argsort(importances)[::-1]
    if isinstance(selector, LassoSelector):
        order = order[importances[order] != 0]
    position = np.full(len(importances), np.inf)
    position[order] = np.arange(1, len(order) + 1)
    return position[truth]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--n-splits', type=int, default=2)
    parser.add_argument('--out', required=True, help='Markdown file to write')
    args = parser.parse_args()

    X, y = load_xy(target='pam50 subtype')
    truth = np.flatnonzero(X.columns.isin(PAM50_GENES))
    assert len(truth) == 50
    n_genes = X.shape[1]
    X, y = X.values, y.values

    rows = []
    splits = StratifiedShuffleSplit(n_splits=args.n_splits, train_size=0.5, random_state=SEED)
    for split, (train, _) in enumerate(splits.split(X, y)):
        X_train = SimpleImputer(strategy='median').fit_transform(X[train])
        X_train = StandardScaler().fit_transform(X_train)
        for task, y_task in build_tasks(y):
            for name, selector in methods(SEED + split).items():
                selector.fit(X_train, y_task[train])
                ranks = ranks_of(selector, truth)
                rows.append({'split': split, 'task': task, 'method': name,
                             **{k: np.mean(ranks <= k) for k in K_VALUES},
                             'rank_50pct': np.quantile(ranks, 0.5, method='inverted_cdf'),
                             'rank_90pct': np.quantile(ranks, 0.9, method='inverted_cdf')})
                print(split, task, name, f"recall@50 {rows[-1][50]:.2f}", flush=True)

    df = pd.DataFrame(rows)
    order = list(methods(SEED))
    random = pd.Series({k: k / n_genes for k in K_VALUES}, name='Random (expected)')

    curve = df.groupby('method')[K_VALUES].mean().reindex(order)
    curve = pd.concat([random.to_frame().T, curve]).round(2)
    per_task = df.groupby(['method', 'task'])[50].mean().unstack().reindex(order).round(2)
    depth = df.groupby('method')[['rank_50pct', 'rank_90pct']].median().reindex(order)

    def markdown(table, index_name):
        header = [index_name, *map(str, table.columns)]
        lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
        lines += ['| ' + ' | '.join([str(i), *map(str, r)]) + ' |' for i, r in table.iterrows()]
        return '\n'.join(lines)

    body = (
        f'SCAN-B, {n_genes} genes, {args.n_splits} splits at train fraction 0.5, the five '
        f'subtype-vs-rest tasks. Generated by `scripts/pam50_recovery.py`.\n\n'
        '## Recall of the 50 PAM50 genes in the top k, mean over tasks and splits\n\n'
        + markdown(curve, 'k') + '\n\n'
        '## Recall at k = 50, per task, mean over splits\n\n'
        + markdown(per_task, 'method') + '\n\n'
        '## Rank by which half and 90% of the 50 are found, median over tasks and splits\n\n'
        '`inf`: never ranked (Lasso ranks only non-zero weights).\n\n'
        + markdown(depth, 'method') + '\n'
    )
    with open(args.out, 'w') as f:
        f.write(body)
    print(body)


if __name__ == '__main__':
    main()
